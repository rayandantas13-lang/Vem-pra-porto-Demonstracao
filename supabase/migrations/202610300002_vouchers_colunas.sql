-- Preserva a tabela operacional e o JSON completo usado pelo aplicativo.
-- As colunas geradas são somente leitura e acompanham automaticamente o JSON.
create function public.vpp_nomes_clientes(v jsonb) returns text
language sql immutable parallel safe set search_path = pg_catalog as $$
  select string_agg(c, ', ' order by ord)
  from jsonb_array_elements_text(case when jsonb_typeof(v->'clientes') = 'array' then v->'clientes' else '[]'::jsonb end) with ordinality as clientes(c, ord)
$$;

create function public.vpp_nomes_passeios(v jsonb) returns text
language sql immutable parallel safe set search_path = pg_catalog as $$
  select string_agg(p->>'nome', ' + ' order by ord)
  from jsonb_array_elements(case when jsonb_typeof(v->'passeios') = 'array' then v->'passeios' else '[]'::jsonb end) with ordinality as passeios(p, ord)
$$;

create function public.vpp_datas_passeios(v jsonb) returns text
language sql immutable parallel safe set search_path = pg_catalog as $$
  select string_agg(distinct d, ' / ' order by d)
  from jsonb_array_elements(case when jsonb_typeof(v->'passeios') = 'array' then v->'passeios' else '[]'::jsonb end) as passeio(p)
  cross join lateral (values (p->>'data'), (p->>'dataVolta')) as datas(d)
  where coalesce(d, '') <> ''
$$;

alter table public.vpp_vouchers
  add column numero bigint generated by default as identity,
  add column codigo text generated always as (data->>'codigo') stored,
  add column clientes text generated always as (public.vpp_nomes_clientes(data)) stored,
  add column pessoas text generated always as (data->>'pessoas') stored,
  add column hotel text generated always as (data->>'hotel') stored,
  add column telefone text generated always as (data->>'telefone') stored,
  add column passeios text generated always as (public.vpp_nomes_passeios(data)) stored,
  add column datas text generated always as (public.vpp_datas_passeios(data)) stored,
  add column total text generated always as (data->>'total') stored,
  add column entrada text generated always as (data->>'entrada') stored,
  add column a_receber text generated always as (data->>'aReceber') stored,
  add column status text generated always as (data->>'status') stored;

-- Mantém a numeração da visão anterior, com a sequência pronta para novos vouchers.
update public.vpp_vouchers v set numero = t.numero
from (
  select id, row_number() over (order by data->>'criadoEm', id) as numero
  from public.vpp_vouchers
) t where v.id = t.id;

drop view public.vpp_vouchers_tabela;
